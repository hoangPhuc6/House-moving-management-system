-- 1. Đổi trạng thái PENDING_SURVEY -> PENDING
UPDATE "bookings" SET "status" = 'PENDING' WHERE "status" = 'PENDING_SURVEY';
UPDATE "booking_status_history" SET "old_status" = 'PENDING' WHERE "old_status" = 'PENDING_SURVEY';
UPDATE "booking_status_history" SET "new_status" = 'PENDING' WHERE "new_status" = 'PENDING_SURVEY';
ALTER TABLE "bookings" ALTER COLUMN "status" SET DEFAULT 'PENDING';

-- 2. Bảng quotations (Các phiên bản báo giá của đơn)
CREATE TABLE IF NOT EXISTS "quotations" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "booking_id" int NOT NULL,
  "version" int NOT NULL,
  "amount" decimal(12,2) NOT NULL,
  "discount_amount" decimal(12,2) NOT NULL DEFAULT 0,
  "final_amount" decimal(12,2) NOT NULL,
  "status" varchar(30) NOT NULL DEFAULT 'DRAFT',
  "note" text,
  "valid_until" timestamp,
  "created_by" bigint,
  "accepted_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_quotations_booking FOREIGN KEY ("booking_id") REFERENCES "bookings" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_quotations_created_by FOREIGN KEY ("created_by") REFERENCES "users" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT uq_quotations_booking_version UNIQUE ("booking_id", "version"),
  CONSTRAINT chk_quotations_version CHECK (version > 0),
  CONSTRAINT chk_quotations_amount CHECK (amount >= 0),
  CONSTRAINT chk_quotations_discount_amount CHECK (discount_amount >= 0),
  CONSTRAINT chk_quotations_final_amount CHECK (final_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_quotations_booking_id ON "quotations" ("booking_id");
CREATE INDEX IF NOT EXISTS idx_quotations_booking_status ON "quotations" ("booking_id", "status");

-- 3. Bảng quotation_items (Dòng chi tiết snapshot của từng báo giá)
CREATE TABLE IF NOT EXISTS "quotation_items" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "quotation_id" int NOT NULL,
  "booking_item_id" int,
  "item_name" varchar(255) NOT NULL,
  "quantity" int NOT NULL DEFAULT 1,
  "unit" varchar(50),
  "unit_price" decimal(12,2) NOT NULL,
  "line_amount" decimal(12,2) NOT NULL,
  "estimated_volume_m3" decimal(10,2),
  "note" text,
  CONSTRAINT fk_quotation_items_quotation FOREIGN KEY ("quotation_id") REFERENCES "quotations" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_quotation_items_booking_item FOREIGN KEY ("booking_item_id") REFERENCES "booking_items" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT chk_quotation_items_quantity CHECK (quantity > 0),
  CONSTRAINT chk_quotation_items_unit_price CHECK (unit_price >= 0),
  CONSTRAINT chk_quotation_items_line_amount CHECK (line_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_quotation_items_quotation_id ON "quotation_items" ("quotation_id");
CREATE INDEX IF NOT EXISTS idx_quotation_items_booking_item_id ON "quotation_items" ("booking_item_id");
