-- Tables: materials, booking_material_allocations, inventory_transactions
--   materials                    : danh mục vật tư + tồn kho hiện tại (1 kho)
--   booking_material_allocations : vật tư cấp cho từng chuyến, cập nhật dần đến khi chốt
--   inventory_transactions       : sổ nhật ký mọi lần tồn kho thay đổi, chỉ INSERT, không sửa/xóa
-- category / status / transaction_type dùng varchar + Java enum (giống V15, V16)
