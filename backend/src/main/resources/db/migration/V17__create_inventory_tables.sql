-- -----------------------------------------------------------------------------
-- 1. Danh mục vật tư
--    CONSUMABLE: thùng carton, băng keo, màng PE, xốp hơi... dùng xong là hết
--    TOOL      : xe đẩy, dây chằng, chăn bọc, bộ tháo lắp... phải hoàn kho
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "materials" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "code" varchar(50) NOT NULL,
  "name" varchar(255) NOT NULL,
  "category" varchar(20) NOT NULL,
  "unit" varchar(30) NOT NULL,                       -- cái, cuộn, mét, bộ...
  "unit_price" decimal(12,2) NOT NULL DEFAULT 0,      -- giá tính khách khi dùng vật tư tiêu hao (0 = miễn phí)
  "quantity_on_hand" int NOT NULL DEFAULT 0,          -- tồn kho hiện tại, chỉ đổi cùng lúc với 1 dòng inventory_transactions
  "min_stock" int NOT NULL DEFAULT 0,                 -- dưới mức này thì cảnh báo tồn thấp
  "description" text,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_materials_code UNIQUE ("code"),
  CONSTRAINT chk_materials_category CHECK (category IN ('CONSUMABLE', 'TOOL')),
  CONSTRAINT chk_materials_quantity CHECK (quantity_on_hand >= 0),
  CONSTRAINT chk_materials_min_stock CHECK (min_stock >= 0),
  CONSTRAINT chk_materials_unit_price CHECK (unit_price >= 0)
);
CREATE INDEX IF NOT EXISTS idx_materials_category_active ON "materials" ("category", "is_active");

-- -----------------------------------------------------------------------------
-- 2. Cấp phát vật tư theo chuyến
--    ALLOCATED: đã xuất, đội vận chuyển đang giữ
--    SETTLED  : đã chốt sau chuyến (used + returned + damaged = allocated)
--    CANCELLED: hủy cấp phát (chuyến/đơn bị hủy, toàn bộ đã hoàn kho)
--    TOOL thì quantity_used phải = 0 (kiểm tra ở service vì CHECK không đọc được bảng materials)
--    Tiền vật tư: khi chốt, service cộng charged_amount vào bookings.total_amount trong cùng transaction
--    (giống V16: phụ phí được khách xác nhận cũng cộng vào bookings.total_amount)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "booking_material_allocations" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "booking_id" int NOT NULL,
  "schedule_id" int NOT NULL,
  "material_id" int NOT NULL,
  "quantity_allocated" int NOT NULL,
  "quantity_used" int NOT NULL DEFAULT 0,            -- vật tư tiêu hao đã dùng hết
  "quantity_returned" int NOT NULL DEFAULT 0,        -- đã hoàn về kho
  "quantity_damaged" int NOT NULL DEFAULT 0,         -- hư / mất ngoài chuyến
  "status" varchar(20) NOT NULL DEFAULT 'ALLOCATED',
  "unit_price" decimal(12,2) NOT NULL DEFAULT 0,     -- giá chốt tại lúc cấp (copy từ materials.unit_price, giá sau này đổi không ảnh hưởng)
  "charged_amount" decimal(12,2),                    -- = quantity_used * unit_price, đã cộng vào bookings.total_amount; NULL = chưa cộng
  "charged_at" timestamp,
  "note" text,
  "allocated_by" bigint,
  "allocated_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "settled_by" bigint,
  "settled_at" timestamp,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_material_allocations_booking FOREIGN KEY ("booking_id") REFERENCES "bookings" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_material_allocations_schedule FOREIGN KEY ("schedule_id") REFERENCES "moving_schedules" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_material_allocations_material FOREIGN KEY ("material_id") REFERENCES "materials" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_material_allocations_allocated_by FOREIGN KEY ("allocated_by") REFERENCES "users" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_material_allocations_settled_by FOREIGN KEY ("settled_by") REFERENCES "users" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT chk_material_allocations_status CHECK (status IN ('ALLOCATED', 'SETTLED', 'CANCELLED')),
  CONSTRAINT chk_material_allocations_quantities CHECK (
    quantity_allocated > 0 AND quantity_used >= 0 AND quantity_returned >= 0 AND quantity_damaged >= 0
    AND quantity_used + quantity_returned + quantity_damaged <= quantity_allocated),
  CONSTRAINT chk_material_allocations_settled CHECK (
    status <> 'SETTLED'
    OR (settled_at IS NOT NULL AND quantity_used + quantity_returned + quantity_damaged = quantity_allocated)),
  CONSTRAINT chk_material_allocations_cancelled CHECK (
    status <> 'CANCELLED' OR quantity_returned = quantity_allocated),
  CONSTRAINT chk_material_allocations_unit_price CHECK (unit_price >= 0),
  -- Chỉ cộng tiền vào booking 1 lần, khi đã chốt, và đúng bằng số đã dùng × giá chốt
  CONSTRAINT chk_material_allocations_charged CHECK (
    (charged_amount IS NULL AND charged_at IS NULL)
    OR (status = 'SETTLED' AND charged_at IS NOT NULL AND charged_amount = quantity_used * unit_price))
);
-- Mỗi chuyến chỉ có 1 dòng đang hiệu lực cho mỗi vật tư; cấp thêm thì tăng quantity_allocated
CREATE UNIQUE INDEX IF NOT EXISTS uq_material_allocations_schedule_material
  ON "booking_material_allocations" ("schedule_id", "material_id") WHERE status <> 'CANCELLED';
CREATE INDEX IF NOT EXISTS idx_material_allocations_booking ON "booking_material_allocations" ("booking_id");
CREATE INDEX IF NOT EXISTS idx_material_allocations_material_status ON "booking_material_allocations" ("material_id", "status");

-- -----------------------------------------------------------------------------
-- 3. Lịch sử giao dịch kho
--    quantity        : số lượng của nghiệp vụ, luôn dương
--    quantity_change : thay đổi thật của tồn kho (+ / - / 0)
--      IMPORT  : +quantity                 nhập hàng
--      EXPORT  : -quantity                 cấp cho chuyến
--      RETURN  : +quantity                 hoàn về kho
--      DAMAGED : 0 nếu hư/mất ngoài chuyến (đã trừ lúc EXPORT), -quantity nếu hư trong kho
--      ADJUST  : +/- quantity              kiểm kê lệch, bắt buộc ghi lý do
--    balance_after   : tồn kho sau giao dịch, để đối soát
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "inventory_transactions" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "material_id" int NOT NULL,
  "transaction_type" varchar(20) NOT NULL,
  "quantity" int NOT NULL,
  "quantity_change" int NOT NULL,
  "balance_after" int NOT NULL,
  "unit_cost" decimal(12,2),                         -- giá nhập, dùng cho IMPORT
  "booking_id" int,
  "schedule_id" int,
  "allocation_id" int,
  "note" text,
  "created_by" bigint,
  "created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_inventory_transactions_material FOREIGN KEY ("material_id") REFERENCES "materials" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_inventory_transactions_booking FOREIGN KEY ("booking_id") REFERENCES "bookings" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_inventory_transactions_schedule FOREIGN KEY ("schedule_id") REFERENCES "moving_schedules" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_inventory_transactions_allocation FOREIGN KEY ("allocation_id") REFERENCES "booking_material_allocations" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_inventory_transactions_created_by FOREIGN KEY ("created_by") REFERENCES "users" ("id") DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT chk_inventory_transactions_type CHECK (transaction_type IN ('IMPORT', 'EXPORT', 'RETURN', 'DAMAGED', 'ADJUST')),
  CONSTRAINT chk_inventory_transactions_quantity CHECK (quantity > 0),
  CONSTRAINT chk_inventory_transactions_balance CHECK (balance_after >= 0),
  CONSTRAINT chk_inventory_transactions_change CHECK (
       (transaction_type IN ('IMPORT', 'RETURN') AND quantity_change = quantity)
    OR (transaction_type = 'EXPORT'              AND quantity_change = -quantity)
    OR (transaction_type = 'DAMAGED'             AND quantity_change IN (0, -quantity))
    OR (transaction_type = 'ADJUST'              AND quantity_change IN (quantity, -quantity))),
  CONSTRAINT chk_inventory_transactions_allocation CHECK (
    transaction_type NOT IN ('EXPORT', 'RETURN') OR allocation_id IS NOT NULL),
  CONSTRAINT chk_inventory_transactions_unit_cost CHECK (unit_cost IS NULL OR unit_cost >= 0),
  CONSTRAINT chk_inventory_transactions_adjust_note CHECK (transaction_type <> 'ADJUST' OR note IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_inventory_transactions_material_created ON "inventory_transactions" ("material_id", "created_at");
CREATE INDEX IF NOT EXISTS idx_inventory_transactions_type_created ON "inventory_transactions" ("transaction_type", "created_at");
CREATE INDEX IF NOT EXISTS idx_inventory_transactions_booking ON "inventory_transactions" ("booking_id");
CREATE INDEX IF NOT EXISTS idx_inventory_transactions_allocation ON "inventory_transactions" ("allocation_id");
